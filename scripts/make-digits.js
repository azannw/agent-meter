'use strict';
// Renders the tray icon's characters (0-9, the no-data dash, "!") with the Windows
// UI font into alpha masks, once per tray size, so the main process, which has no
// canvas, can draw the number at runtime. The masks are rendered at whole-pixel
// pen positions and composed at whole-pixel offsets, so nothing is resampled.
// Usage: electron scripts/make-digits.js   (writes src/main/digits.js)
const fs = require('node:fs');
const path = require('node:path');
const { app, BrowserWindow } = require('electron');

const SPEC = {
  family: 'Segoe UI Variable Display',
  weight: 600,
  sizes: [16, 20, 24, 28, 32, 40, 48], // 16 px x every Windows scale tray.js builds
  // class, font size as a share of the cell, characters
  classes: [
    ['two', 0.55, '0123456789'],
    ['one', 0.625, '0123456789–'],
    ['bang', 0.65, '!'],
  ],
};

// Runs in the page.
function render(spec) {
  const c = document.createElement('canvas');
  const ctx = c.getContext('2d', { willReadFrequently: true });
  const fontOk = document.fonts.check(`${spec.weight} 12px "${spec.family}"`);
  const sizes = {};
  for (const S of spec.sizes) {
    const entry = {};
    for (const [cls, ratio, chars] of spec.classes) {
      const px = Math.round(S * ratio * 2) / 2;
      const glyphs = {};
      for (const ch of chars) {
        const W = S * 2;
        c.width = W;
        c.height = W;
        ctx.font = `${spec.weight} ${px}px "${spec.family}", "Segoe UI", sans-serif`;
        ctx.fillStyle = '#ffffff';
        ctx.textBaseline = 'alphabetic';
        const ox = Math.round(S * 0.5);
        const base = Math.round(S * 1.4);
        ctx.fillText(ch, ox, base);
        const img = ctx.getImageData(0, 0, W, W).data;
        let x0 = W, y0 = W, x1 = -1, y1 = -1;
        for (let y = 0; y < W; y++) {
          for (let x = 0; x < W; x++) {
            if (!img[(y * W + x) * 4 + 3]) continue;
            if (x < x0) x0 = x;
            if (x > x1) x1 = x;
            if (y < y0) y0 = y;
            if (y > y1) y1 = y;
          }
        }
        const w = x1 - x0 + 1;
        const h = y1 - y0 + 1;
        let bin = '';
        for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) bin += String.fromCharCode(img[((y0 + y) * W + (x0 + x)) * 4 + 3]);
        glyphs[ch] = { adv: Math.round(ctx.measureText(ch).width * 100) / 100, x: x0 - ox, y: y0 - base, w, h, a: btoa(bin) };
      }
      entry[cls] = { px, glyphs };
    }
    sizes[S] = entry;
  }
  return { fontOk, sizes };
}

app.whenReady().then(async () => {
  const win = new BrowserWindow({ show: false, width: 200, height: 200 });
  await win.loadURL('data:text/html,<meta charset=utf-8><body></body>');
  const { fontOk, sizes } = await win.webContents.executeJavaScript(`(${render.toString()})(${JSON.stringify(SPEC)})`);
  if (!fontOk) console.warn(`"${SPEC.family}" is not installed: masks use the fallback font`);
  const out = path.join(__dirname, '..', 'src', 'main', 'digits.js');
  const font = `${fontOk ? SPEC.family : 'Segoe UI'} ${SPEC.weight}`;
  const body = JSON.stringify({ font, sizes });
  fs.writeFileSync(
    out,
    "'use strict';\n" +
      `// Generated by scripts/make-digits.js (${font}): alpha masks for the tray icon's\n` +
      '// number at every tray size. Do not edit; re-run the script.\n' +
      `module.exports = ${body};\n`,
  );
  console.log('wrote', out, Math.round(body.length / 1024) + ' KB', font);
  app.quit();
});
